class WasteType(models.TextChoices):
    LIQUID = 'LIQUID', 'Liquid'
    SOLID = 'SOLID', 'Solid'


class WasteClass(models.TextChoices):
    VLLW = 'VLLW', 'Very Low Level Waste'
    LLW = 'LLW', 'Low Level Waste'
    ILW = 'ILW', 'Intermediate Level Waste'
    HLW = 'HLW', 'High Level Waste'


class WasteState(models.TextChoices):
    UNPROCESSED = 'UNPROCESSED', 'Unprocessed'
    PROCESSED = 'PROCESSED', 'Processed'
    CONDITIONED = 'CONDITIONED', 'Conditioned'


class Facility(models.TextChoices):
    TEHRAN = 'TEHRAN', 'Tehran'
    KARAJ = 'KARAJ', 'Karaj'
    ANARAK = 'ANARAK', 'Anarak'


class OriginOfWaste(models.TextChoices):
    RECEIVED = 'RECEIVED', 'Received'
    HISTORICAL = 'HISTORICAL', 'Historical'
    GENERATED = 'GENERATED', 'Generated by Home Facility'
    PROCESSING = 'PROCESSING', 'Generated by Processing'


class BatchStatus(models.TextChoices):
    ACTIVE = 'ACTIVE', 'Active'
    RELEASED = 'RELEASED', 'Released'
    CONSUMED = 'CONSUMED', 'Consumed'
    STORED = 'STORED', 'Stored'


class TreatmentOption(models.TextChoices):
    CHEMICAL = 'CHEMICAL', 'Chemical Treatment'
    SEDIMENTATION = 'SEDIMENTATION', 'Sedimentation'
    FILTRATION = 'FILTRATION', 'Filtration'
    CEMENTATION = 'CEMENTATION', 'Cementation'
    INCINERATION = 'INCINERATION', 'Incineration'


