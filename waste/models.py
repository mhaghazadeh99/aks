class LiquidWasteDetails(models.Model):

    batch = models.OneToOneField(
        WasteBatch,
        on_delete=models.CASCADE,
        related_name='liquid_details'
    )

    ph = models.DecimalField(
        max_digits=5,
        decimal_places=2,
        blank=True,
        null=True
    )

    density = models.DecimalField(
        max_digits=10,
        decimal_places=4,
        blank=True,
        null=True
    )

    total_solids = models.DecimalField(
        max_digits=10,
        decimal_places=4,
        blank=True,
        null=True
    )

    suspended_solids = models.DecimalField(
        max_digits=10,
        decimal_places=4,
        blank=True,
        null=True
    )

    soluble_solids = models.DecimalField(
        max_digits=10,
        decimal_places=4,
        blank=True,
        null=True
    )

    possible_treatment = models.CharField(
        max_length=30,
        choices=TreatmentOption.choices,
        blank=True,
        null=True
    )

# Conditioning Information
class WasteConditioning(models.Model):

    batch = models.OneToOneField(
        WasteBatch,
        on_delete=models.CASCADE,
        related_name='conditioning'
    )

    pretreatment = models.CharField(
        max_length=30,
        choices=TreatmentOption.choices,
        blank=True,
        null=True)

    treatment = models.CharField(
        max_length=30,
        choices=TreatmentOption.choices,
        blank=True,
        null=True)

    further_conditioning_planned = models.CharField(
        max_length=50,
        blank=True,
        null=True
    )

    conditioning_matrix = models.CharField(
        max_length=50,
        blank=True,
        null=True
    )

    waste_to_matrix_ratio = models.DecimalField(
        max_digits=10,
        decimal_places=4,
        blank=True,
        null=True
    )




class BatchActivitySnapshot(models.Model):

    batch = models.ForeignKey(
        WasteBatch,
        on_delete=models.CASCADE,
        related_name='activity_snapshots'
    )

    analysis = models.ForeignKey(
        'laboratory.Analysis',
        on_delete=models.CASCADE
    )

    alpha_bq = models.DecimalField(
        max_digits=20,
        decimal_places=5
    )

    beta_bq = models.DecimalField(
        max_digits=20,
        decimal_places=5
    )

    gamma_bq = models.DecimalField(
        max_digits=20,
        decimal_places=5
    )

    total_activity_bq = models.DecimalField(
        max_digits=20,
        decimal_places=5
    )

    created_at = models.DateTimeField(
        auto_now_add=True
    )

    class Meta:
        ordering = ['-created_at']


















